# shellcheck shell=bash
# Shared helpers for the INM one-command operations. Sourced, never executed directly.
set -Eeuo pipefail
umask 027

ROOT="$(cd "$(dirname "${BASH_SOURCE[0]}")/../.." && pwd)"
ETC="${INM_ETC_DIR:-/etc/inm}"
STATE="${INM_STATE_DIR:-/var/lib/inm}"
LOG_DIR="${INM_LOG_DIR:-/var/log/inm}"
ENV_FILE="$ETC/inm.env"
# shellcheck disable=SC2034  # used by backup.sh / install.sh, which source this file
BACKUP_DIR="${INM_BACKUP_DIR:-$STATE/backups}"
PROJECT=inm

log()  { printf '%s [inm] %s\n' "$(date -u +%Y-%m-%dT%H:%M:%SZ)" "$*"; }
warn() { printf '%s [inm] WARNING: %s\n' "$(date -u +%Y-%m-%dT%H:%M:%SZ)" "$*" >&2; }
die()  { printf '%s [inm] ERROR: %s\n' "$(date -u +%Y-%m-%dT%H:%M:%SZ)" "$1" >&2; exit "${2:-1}"; }

require_root() { [[ $EUID -eq 0 ]] || die "run with sudo (root is needed for Docker, /etc/inm and firewall checks)" 2; }

operator_name() {
  # The named human who ran the command (sudo preserves it). Never a shared service identity.
  local who="${INM_OPERATOR:-${SUDO_USER:-}}"
  [[ -n "$who" && "$who" != root ]] || who="root (direct root shell: run via sudo as your own account)"
  printf '%s' "$who"
}

release_version() { tr -d '[:space:]' < "$ROOT/VERSION"; }
git_commit() { git -C "$ROOT" rev-parse HEAD 2>/dev/null || echo unknown; }

start_transcript() {  # $1 = operation; tees all output to /var/log/inm/<op>-<ts>.log (no secrets are ever printed)
  mkdir -p "$LOG_DIR"; chmod 0750 "$LOG_DIR"
  TRANSCRIPT="$LOG_DIR/$1-$(date -u +%Y%m%dT%H%M%SZ).log"
  exec > >(tee -a "$TRANSCRIPT") 2>&1
  log "operation=$1 operator=$(operator_name) version=$(release_version) commit=$(git_commit) host=$(hostname)"
}

compose() {
  docker compose --project-name "$PROJECT" --project-directory "$ROOT" -f "$ROOT/compose.yaml" --env-file "$ENV_FILE" "$@"
}

env_get() { grep -E "^$1=" "$ENV_FILE" | head -1 | cut -d= -f2-; }

set_env_value() {  # non-secret values only (version, commit)
  local key=$1 val=$2
  if grep -qE "^$key=" "$ENV_FILE"; then sed -i "s|^$key=.*|$key=$val|" "$ENV_FILE"; else echo "$key=$val" >> "$ENV_FILE"; fi
}

rand() { openssl rand -base64 48 | tr -dc 'A-Za-z0-9' | head -c "${1:-40}"; }

generate_secrets() {
  # Idempotent: an existing env file is never regenerated (P1-DEP-02). Values are never echoed (P1-DEP-04).
  install -d -m 0700 "$ETC"
  if [[ -f "$ENV_FILE" ]]; then
    log "secrets: existing $ENV_FILE kept (not regenerated)"
    return 0
  fi
  local fernet admin
  fernet="$(openssl rand -base64 32 | tr '+/' '-_')"
  admin="$(rand 20)"
  local tmp; tmp="$(mktemp "$ETC/.inm.env.XXXXXX")"
  chmod 0600 "$tmp"
  cat > "$tmp" <<EOF
# Generated by install.sh on $(date -u +%Y-%m-%dT%H:%M:%SZ). Mode 0600. Never commit, print or e-mail this file.
INM_VERSION=$(release_version)
INM_GIT_COMMIT=$(git_commit)
INM_PROFILE=demo
INM_WEB_BIND=${INM_WEB_BIND:-127.0.0.1}
INM_WEB_PORT=${INM_WEB_PORT:-8443}
INM_SYSLOG_BIND=${INM_SYSLOG_BIND:-127.0.0.1}
INM_SYSLOG_PORT=${INM_SYSLOG_PORT:-1514}
INM_TLS_DIR=$ETC/tls
INM_POLL_INTERVAL_SECONDS=60
INM_ADMIN_USERNAME=admin
MGMT_DB_PASSWORD=$(rand 40)
TS_DB_PASSWORD=$(rand 40)
# NATS unquoted environment substitutions may fail when a password starts
# with a digit; force an alphabetic prefix (random suffix remains secret).
INM_NATS_API_PASSWORD=nats$(rand 40)
INM_NATS_WORKER_PASSWORD=nats$(rand 40)
INM_AI_SHARED_TOKEN=$(rand 48)
SIMS_JWT_SECRET=$(rand 64)
SIMS_FERNET_KEY=$fernet
SIMS_ADMIN_PASSWORD=$admin
EOF
  mv "$tmp" "$ENV_FILE"
  ( umask 077; printf '%s\n' "$admin" > "$ETC/initial-admin-password" )
  chmod 0600 "$ETC/initial-admin-password"
  [[ -f "$ETC/backup.key" ]] || { ( umask 077; openssl rand -base64 48 > "$ETC/backup.key" ); chmod 0600 "$ETC/backup.key"; }
  log "secrets: generated $ENV_FILE (0600), initial admin password in $ETC/initial-admin-password (0600), backup key in $ETC/backup.key (0600)"
}

ensure_tls() {
  install -d -m 0700 "$ETC/tls"
  if [[ -f "$ETC/tls/tls.crt" && -f "$ETC/tls/tls.key" ]]; then log "tls: existing certificate kept"; return 0; fi
  openssl req -x509 -newkey rsa:3072 -sha256 -days 397 -nodes -subj "/CN=$(hostname -f 2>/dev/null || hostname)" \
    -addext "subjectAltName=DNS:$(hostname),DNS:localhost,IP:127.0.0.1" \
    -keyout "$ETC/tls/tls.key" -out "$ETC/tls/tls.crt" >/dev/null 2>&1
  chmod 0600 "$ETC/tls/tls.key"; chmod 0644 "$ETC/tls/tls.crt"
  log "tls: generated a self-signed certificate (replace $ETC/tls/tls.crt and tls.key with your CA-issued pair)"
}

port_owner() {  # prints the process listening on TCP/UDP port $1, if any
  if command -v ss >/dev/null; then
    ss -H -lntup 2>/dev/null | awk -v p=":$1" '$5 ~ p"$" {print $0}' | head -1
  else  # minimal images without iproute: a failed bind means something holds the port
    python3 -I -c 'import socket,sys
for kind in (socket.SOCK_STREAM, socket.SOCK_DGRAM):
    s=socket.socket(socket.AF_INET, kind)
    try: s.bind(("0.0.0.0", int(sys.argv[1])))
    except OSError: print(f"port {sys.argv[1]} in use (process unknown: install iproute for details)"); break
    finally: s.close()' "$1"
  fi
}

check_ports_free() {
  # P1-DEP-12: fail before exposing or altering anything if a port is held by something that is not INM.
  local port bad=0 owner
  for port in "$@"; do
    owner="$(port_owner "$port")"
    if [[ -n "$owner" ]] && ! grep -q 'docker-proxy\|docker' <<<"$owner"; then
      warn "port $port is already in use: $owner"; bad=1
    elif [[ -n "$owner" ]] && ! docker ps --format '{{.Names}} {{.Ports}}' 2>/dev/null | grep -q "^${PROJECT}-.*:$port->"; then
      warn "port $port is held by another Docker container"; bad=1
    fi
  done
  [[ $bad -eq 0 ]] || die "preflight failed: required port(s) in use. Nothing was installed or changed." 4
}

images_lock() {
  # Record exactly which image digests are running (P1-DEP: release receipt; digest pinning on reinstall).
  local out="$STATE/images.lock"
  install -d -m 0750 "$STATE"
  compose images --format json 2>/dev/null > "$STATE/.images.json" || true
  {
    echo "# Resolved $(date -u +%Y-%m-%dT%H:%M:%SZ) for $(release_version) ($(git_commit))"
    for svc in management-db timeseries-db nats loki alloy api worker ai web; do
      local cid img digest
      cid="$(compose ps -q "$svc" 2>/dev/null | head -1)"
      [[ -n "$cid" ]] || continue
      img="$(docker inspect --format '{{.Config.Image}}' "$cid")"
      digest="$(docker image inspect --format '{{if .RepoDigests}}{{index .RepoDigests 0}}{{else}}{{.Id}}{{end}}' "$img" 2>/dev/null || echo unknown)"
      echo "$svc $img $digest"
    done
  } > "$out"
  chmod 0640 "$out"
}

digests_json() {
  python3 -I -c 'import json,sys
out={}
for line in open(sys.argv[1]):
    if line.startswith("#") or not line.strip(): continue
    s,i,d=line.split()[:3]; out[s]=d
print(json.dumps(out))' "$STATE/images.lock" 2>/dev/null || echo '{}'
}

record_release() {  # $1 operation  $2 outcome  [$3 detail]
  local op=$1 outcome=$2 detail="${3:-}"
  install -d -m 0750 "$STATE"
  # Always keep a local receipt, even when the database is unavailable.
  python3 -I -c 'import json,sys,datetime
print(json.dumps({"ts":datetime.datetime.now(datetime.timezone.utc).isoformat(),"operation":sys.argv[1],"outcome":sys.argv[2],
 "operator":sys.argv[3],"version":sys.argv[4],"commit":sys.argv[5],"detail":sys.argv[6]}))' \
    "$op" "$outcome" "$(operator_name)" "$(release_version)" "$(git_commit)" "$detail" >> "$STATE/receipts.jsonl"
  # And an audited receipt in the management database when the API container is up.
  if compose ps --status running api 2>/dev/null | grep -q api; then
    compose exec -T api python -m backend.cli record-release --operation "$op" --operator "$(operator_name)" \
      --version "$(release_version)" --commit "$(git_commit)" --outcome "$outcome" \
      --digests-json "$(digests_json)" --detail "${detail:0:500}" >/dev/null \
      || warn "could not write the release receipt to the database (local receipt kept in $STATE/receipts.jsonl)"
  else
    warn "API not running: release receipt kept locally in $STATE/receipts.jsonl only"
  fi
}

schema_status() { compose exec -T api python -m backend.cli schema-status 2>/dev/null | tail -1; }
