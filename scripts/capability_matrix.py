"""Generate docs/CAPABILITY_MATRIX_1.2.0_RC2.md from the code that serves /capability-matrix and /system/features,
plus the emulated certification evidence. Nothing here is typed by hand, so the document cannot claim more than the
software does. Hardware certification is read from the evidence: there is none in this release."""
from __future__ import annotations

import json
import os
import sys
from pathlib import Path

ROOT = Path(__file__).resolve().parents[1]
sys.path.insert(0, str(ROOT))
_TMP = Path("/tmp/inm-capmatrix")
_TMP.mkdir(exist_ok=True)
for f in _TMP.glob("*.db"):
    f.unlink()
# isolated, production-default posture: live mode, writes locked, no external services
os.environ.update({"SIMS_MODE": "live", "SIMS_INM_PROFILE": "lab-readonly", "SIMS_DEVICE_WRITE_LOCK": "true",
                   "SIMS_ALLOW_CONFIG_CHANGES": "false", "SIMS_ROLE": "api", "SIMS_DISABLE_SCHEDULER": "true",
                   "SIMS_DATABASE_URL": f"sqlite:///{_TMP / 'mgmt.db'}",
                   "INM_TELEMETRY_DATABASE_URL": f"sqlite:///{_TMP / 'ts.db'}", "INM_VAULT_DIR": str(_TMP / "vault")})
for k in ("INM_NATS_URL", "INM_LOKI_URL", "INM_AI_URL", "INM_AUTOMATIC_OPTIMIZATION"):
    os.environ.pop(k, None)
os.environ.setdefault("SIMS_JWT_SECRET", "m" * 48)
os.environ.setdefault("SIMS_ADMIN_PASSWORD", "capability-matrix-only")


def main() -> int:
    from backend.domain import adapters as A
    runs = json.loads((ROOT / "evidence/certification/emulated_certification_runs.json").read_text())
    emu: dict[str, dict[str, str]] = {}
    for model, r in runs.items():
        for x in r["results"]:
            emu.setdefault(x["operation"], {})[model] = ("PASS" if x["passed"] else
                                                          "UNSUPPORTED" if x.get("unsupported") else "FAIL")
    models = list(runs)
    out = ["# Capability matrix — NetworkManager3 1.2.0-rc2", "",
           "Generated by `scripts/capability_matrix.py` from `backend/domain/adapters.py` (the registry served by "
           "`/api/v1/capability-matrix`), `/api/v1/system/features` and `evidence/certification/`.", "",
           "**Hardware certification: none.** Every operation below is `UNCERTIFIED` for hardware. The emulated "
           "columns are SOFTWARE PASS ONLY (strict protocol emulators); an operation becomes executable on a real "
           "device only after it is certified on that model/firmware train in a lab, independently approved, and "
           "the owner unlocks writes (`INM_DEVICE_WRITE_LOCK=false` + `INM_ALLOW_CONFIG_CHANGES=true`). Hardware "
           "writes stayed locked for this whole campaign.", "",
           "**Device-originated log reads:** Aruba Instant implements read-only show log system/security/user; "
           "CX implements REST /logs/audit and /logs/event. Normalized output is bounded (100 entries), "
           "credential-redacted, and restricted to operator/auditor/administrator. The fixed diagnostic "
           "operations cover RF/clients/system on Instant and port authentication/VSF/PoE/QoS/LACP on CX. "
           "Both are software/emulator tested only; actual device responses remain UNCERTIFIED. "
           "The Device 360 Operations screen uses the protected device-logs and diagnostics APIs. "
           "These are distinct from the platform hash-chained audit trail.", ""]
    for spec in A.REGISTRY:
        p = A.public(spec)
        out += [f"## {p['vendor']} {p['family']} — `{p['key']}`", "",
                f"* Models: {', '.join(p['models']) or 'any'}; firmware {p.get('firmware_min') or '-'} … "
                f"{p.get('firmware_max') or '-'}",
                f"* Protocols: {'; '.join(p['protocols'])}",
                f"* Adapter implemented: **{p['implemented']}**; hardware certification: **{p['certification']}**",
                f"* Notes: {p.get('notes') or ''}", "",
                "| Read / lifecycle operation | Software status |", "|---|---|"]
        out += [f"| {k} | {v} |" for k, v in p["operations"].items()]
        if p["typed_operations"]:
            fam_models = [m for m in models if (m.startswith("CX") if spec.family == "switch" else m.startswith("AP"))]
            out += ["", "| Typed write operation | Software | Hardware | " + " | ".join(f"Emulated {m}" for m in fam_models) + " |",
                    "|---|---|---|" + "---|" * len(fam_models)]
            for op in p["typed_operations"] + ["config.restore"]:
                cells = [emu.get(op, {}).get(m, "not in campaign") for m in fam_models]
                sw = "UNSUPPORTED (guided procedure)" if op == "config.restore" and spec.family == "access_point" else "IMPLEMENTED"
                out.append(f"| {op} | {sw} | UNCERTIFIED | " + " | ".join(cells) + " |")
        out.append("")
    from fastapi.testclient import TestClient
    from backend.main import create_app
    with TestClient(create_app()) as c:
        r = c.post("/api/auth/login", json={"username": "admin", "password": os.environ["SIMS_ADMIN_PASSWORD"]})
        feats = c.get("/api/v1/system/features",
                      headers={"Authorization": f"Bearer {r.json()['access_token']}"}).json() if r.status_code == 200 else None
    if feats:
        out += ["## Module status (`/api/v1/system/features`)", "", f"Hardware writes: **{feats['device_writes']}**", "",
                "| Module | Status | Note |", "|---|---|---|"]
        out += [f"| {m['key']} | {m['status']} | {m.get('note') or ''} |" for m in feats["modules"]]
    (ROOT / "docs" / "CAPABILITY_MATRIX_1.2.0_RC2.md").write_text("\n".join(out) + "\n")
    print("written docs/CAPABILITY_MATRIX_1.2.0_RC2.md")
    return 0


if __name__ == "__main__":
    sys.exit(main())
